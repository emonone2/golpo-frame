const dict = { en, bn }

const ERR: Record<CloudErrorCode, CKey> = {
  not_configured: 'not_configured_title',
  forbidden: 'err_forbidden',
  invalid: 'err_invalid',
  diary_full: 'err_diary_full',
  username_taken: 'err_username_taken',
  not_found: 'err_not_found',
  unknown: 'err_unknown',
}

export function errKey(e: unknown): CKey {
  return e instanceof CloudError ? ERR[e.code] : 'err_unknown'
}

export const DICT_EN = en
export const DICT_BN = bn

/** Translator for the diary/community strings. Supports {name}-style variables. */
export function useCT() {
  const { lang } = useLang()
  return useCallback(
    (key: CKey, vars?: Record<string, string | number>): string => {
      let s: string = dict[lang][key]
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
    [lang],
  )
}
